import { webcrypto } from 'node:crypto';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { encode64, decode64, contextBytes, encryptSession, verificationCode } from '../protocol.mjs';
globalThis.crypto ||= webcrypto;
const sandbox = { console, setTimeout, clearTimeout, Uint8Array, ArrayBuffer }; sandbox.window = sandbox;
vm.createContext(sandbox);
vm.runInContext(readFileSync(new URL('../vendor/forge-1.4.3.min.js', import.meta.url), 'utf8'), sandbox);
globalThis.forge = sandbox.forge;
const key = await crypto.subtle.generateKey({ name: 'RSA-OAEP', modulusLength: 2048, publicExponent: new Uint8Array([1,0,1]), hash: 'SHA-256' }, true, ['wrapKey','unwrapKey']);
const p = { v:1, id:'f'.repeat(43), expiresAt:Date.now()+170000, deviceName:'测试电视', spki:encode64(new Uint8Array(await crypto.subtle.exportKey('spki', key.publicKey))) };
assert.equal(await verificationCode(p, {}), await verificationCode(p));
const s = { auth_token:'synthetic-test', ct0:'synthetic-csrf' };
const e = await encryptSession(p, s, { cryptoApi:{} });
const aes = await crypto.subtle.unwrapKey('raw', decode64(e.wrappedKey), key.privateKey, { name:'RSA-OAEP', label:contextBytes(p) }, {name:'AES-GCM',length:256}, false, ['decrypt']);
const plain = await crypto.subtle.decrypt({name:'AES-GCM',iv:decode64(e.iv),additionalData:contextBytes(p),tagLength:128},aes,decode64(e.ciphertext));
assert.deepEqual(JSON.parse(new TextDecoder().decode(plain)),s);
const changed=decode64(e.ciphertext);changed[0]^=1;
await assert.rejects(crypto.subtle.decrypt({name:'AES-GCM',iv:decode64(e.iv),additionalData:contextBytes(p),tagLength:128},aes,changed));
console.log('PASS: LAN forge/WebCrypto code + OAEP/MGF1/label + AES-GCM interoperability and tamper rejection');
